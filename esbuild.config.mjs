import esbuild from 'esbuild';
import { builtinModules } from 'node:module';
import { promises as fs } from 'node:fs';
import process from 'node:process';

const production = process.argv[2] === 'production';
const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD.
*/
`;

const SCRIPT_ELEMENT = /createElement\(\s*["'`]script["'`]\s*\)/i;

function replaceOnce(source, pattern, replacement) {
	const matches = source.match(new RegExp(pattern.source, `${pattern.flags}g`)) ?? [];
	if (matches.length !== 1) {
		throw new Error(
			`Dark Reader's source changed (${matches.length} matches for ${pattern}); update the proxy patch in esbuild.config.mjs.`,
		);
	}
	return source.replace(pattern, replacement);
}

// Dark Reader starts its stylesheet proxy by inserting an inline <script> that
// holds its own injectProxy() function. The injector already runs inside the
// page, so call injectProxy() directly instead: no script element is created,
// and pages whose content security policy blocks inline scripts get the proxy
// too.
const callProxyDirectly = {
	name: 'darkreader-direct-proxy',
	setup(build) {
		build.onLoad({ filter: /[\\/]darkreader[\\/]darkreader\.mjs$/ }, async (args) => {
			let source = await fs.readFile(args.path, 'utf8');
			source = replaceOnce(
				source,
				/\{\s*const proxyScript = createOrUpdateScript\("darkreader--proxy"\);[\s\S]*?proxyScript\.remove\(\);\s*\}/,
				'try { injectProxy(enableStyleSheetsProxy, enableCustomElementRegistryProxy); } catch (error) { console.error(error); }',
			);
			source = replaceOnce(source, /function createOrUpdateScript\([^)]*\) \{[\s\S]*?\r?\n\}\r?\n/, '');
			return { contents: source, loader: 'js' };
		});
	},
};

const injectedBuild = await esbuild.build({
	entryPoints: ['src/injected.ts'],
	bundle: true,
	platform: 'browser',
	format: 'iife',
	target: 'es2021',
	legalComments: 'eof',
	minify: production,
	write: false,
	plugins: [callProxyDirectly],
});

const injectedCode = injectedBuild.outputFiles?.[0]?.text;
if (!injectedCode) {
	throw new Error('esbuild did not produce the Dark Reader injector.');
}
if (SCRIPT_ELEMENT.test(injectedCode)) {
	throw new Error('The Dark Reader injector still creates a script element.');
}

await fs.writeFile(
	'src/generated-injector.ts',
	`// Generated by esbuild.config.mjs. Do not edit manually.\nexport const DARK_READER_INJECTOR = ${JSON.stringify(injectedCode)};\n`,
);

const context = await esbuild.context({
	banner: { js: banner },
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: production ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: production,
});

if (production) {
	await context.rebuild();
	await context.dispose();
	if (SCRIPT_ELEMENT.test(await fs.readFile('main.js', 'utf8'))) {
		throw new Error('main.js creates a script element, which Obsidian plugin review rejects.');
	}
} else {
	await context.watch();
}
